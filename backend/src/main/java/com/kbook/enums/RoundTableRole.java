    /** 角色口头禅/说话风格标记 */
    private final String catchphrase;

    /** 抢麦权重 1-10（越高越容易抢到话筒） */
    private final int grabWeight;

    /** 话量 1-5（越高说话越多） */
    private final int verbosity;

    /** 主见程度 1-5（越高越坚持自己的立场） */
    private final int opinionated;

    /** 挑战倾向 1-5（越高越喜欢质疑和反驳） */
    private final int challenge;

    /** 共情力 1-5（越高越善于理解他人和情感共鸣） */
    private final int empathy;

    /** 幽默感 1-5（越高越善于调侃和轻松化） */
    private final int humor;

    RoundTableRole(String key, String name, String title, String roleGroup, String prompt,
                   String catchphrase,
                   int grabWeight, int verbosity, int opinionated,
                   int challenge, int empathy, int humor) {
        this.key = key;
        this.name = name;
        this.title = title;
        this.roleGroup = roleGroup;
        this.prompt = prompt;
        this.catchphrase = catchphrase;

        // 参数约束校验
        // 1. 爱挑战的人很难高共情
        if (challenge > 3 && empathy > 3) {
            empathy = 3;
        }
        // 2. 高主见才能高挑战
        if (challenge > opinionated) {
            challenge = opinionated;
        }
        // 3. 话少的人抢麦也没用
        if (verbosity <= 2 && grabWeight >= 8) {
            grabWeight = 7;
        }
        // 4. HOST 特殊规则
        if ("HOST".equals(key)) {
            grabWeight = 10;
            challenge = 1;
            empathy = 5;
            opinionated = 2;
            humor = 3;
        }

        this.grabWeight = grabWeight;
        this.verbosity = verbosity;
        this.opinionated = opinionated;
        this.challenge = challenge;
        this.empathy = empathy;
        this.humor = humor;
    }

    /**
     * 根据 key 查找角色枚举
     *
     * @param key 角色键名
     * @return 对应的角色枚举，未找到返回 null
     */
    public static RoundTableRole fromKey(String key) {
        if (key == null) return null;
        for (RoundTableRole role : values()) {
            if (role.key.equals(key)) return role;
        }
        return null;
    }
